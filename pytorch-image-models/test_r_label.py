def process_imagenet_a_dict():
    labels = [v[0] for _, v in imagenet_a_dict.items()]
    unique_labels = set(labels)
    sorted_labels = list(sorted(unique_labels, key=natural_key))
    # class_to_idx = {c: idx for idx, c in enumerate(sorted_labels)}
    index2class = {idx:c for idx, c in enumerate(sorted_labels)}
    return sorted_labels

def process_imagenet_r_dict():
    labels = [k for k, _ in imagenet_r_dict.items()]
    unique_labels = set(labels)
    sorted_labels = list(sorted(unique_labels, key=natural_key))
    # class_to_idx = {c: idx for idx, c in enumerate(sorted_labels)}
    index2class = {idx:c for idx, c in enumerate(sorted_labels)}
    return sorted_labels

def generate_imagenet_a_mask_1k():
    a_index2class = process_imagenet_a_dict()
    mask = torch.zeros(1000, dtype=torch.bool)
    for i,a_label in enumerate(a_index2class):
        for i in range(1000):
            if imagenet_info.index_to_label_name(i) == a_label:
                mask[i] = True
                break
    return mask
